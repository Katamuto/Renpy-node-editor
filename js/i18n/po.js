/* GETTEXT PO / POT: the universal translation exchange format (Poedit, Weblate, Crowdin, Lokalise, Transifex, OmegaT...).
   One .po per language; msgid = original text, msgstr = translation; "#." lines give translators context. */
(function (R) {
  const I = R.i18n = R.i18n || {};
  const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\t/g, '\\t').replace(/\r/g, '');
  const str = (s) => {
    const parts = String(s).split('\n');
    if (parts.length === 1) return '"' + esc(s) + '"';
    return '""\n' + parts.map((p, i) => '"' + esc(p) + (i < parts.length - 1 ? '\\n' : '') + '"').filter(l => l !== '""').join('\n');
  };

  // lang = {code,name,iso} or null for a template (.pot)
  I.toPO = function (project, lang) {
    const entries = I.collect(project), iso = lang ? (lang.iso || lang.code) : '';
    const out = ['# Translations for ' + project.meta.name + ' (generated by Ren\'Py Node Editor)',
      '# Keep [variables] and {tags} exactly as in the original text.', 'msgid ""', 'msgstr ""',
      '"Project-Id-Version: ' + esc(project.meta.name + ' ' + project.meta.version) + '\\n"',
      '"Language: ' + esc(iso) + '\\n"', '"MIME-Version: 1.0\\n"', '"Content-Type: text/plain; charset=UTF-8\\n"', '"Content-Transfer-Encoding: 8bit\\n"', ''];
    entries.forEach(e => {
      e.notes.forEach(n => out.push('#. ' + n.replace(/\n/g, ' ')));
      out.push('msgid ' + str(e.text), 'msgstr ' + str(lang ? I.get(project, e.text, lang.code) : ''), '');
    });
    return out.join('\n');
  };

  // -> {entries:[{id, str, fuzzy}], iso}
  I.fromPO = function (text) {
    const entries = []; let cur = null, field = null, fuzzy = false, iso = '';
    const un = (q) => q.slice(1, -1).replace(/\\(n|t|"|\\)/g, (m, c) => c === 'n' ? '\n' : c === 't' ? '\t' : c);
    const flush = () => { if (cur && cur.id !== undefined) entries.push(cur); cur = null; field = null; };
    text.replace(/^\uFEFF/, '').split(/\r?\n/).forEach(raw => {
      const line = raw.trim();
      if (!line) { flush(); fuzzy = false; return; }
      if (line.startsWith('#,')) { if (/fuzzy/.test(line)) fuzzy = true; return; }
      if (line.startsWith('#')) return;
      let m;
      if ((m = line.match(/^msgid\s+(".*")$/))) { flush(); cur = { id: un(m[1]), str: '', fuzzy }; field = 'id'; }
      else if ((m = line.match(/^msgstr\s+(".*")$/)) && cur) { cur.str = un(m[1]); field = 'str'; }
      else if ((m = line.match(/^msgctxt\s+/))) { field = null; }
      else if (/^".*"$/.test(line) && cur && field) cur[field] += un(line);
    });
    flush();
    const head = entries.find(e => e.id === ''); if (head) { const l = head.str.match(/^Language:\s*(.+)$/m); if (l) iso = l[1].trim(); }
    return { entries: entries.filter(e => e.id !== ''), iso };
  };

  // Applies parsed entries to one language. Returns counts.
  I.importEntries = function (project, code, entries) {
    const known = new Set(I.collect(project).map(e => e.text).concat(Object.keys(project.translations.strings)));
    let imported = 0, skipped = 0, fuzzy = 0;
    entries.forEach(e => {
      if (!e.str) return;
      if (e.fuzzy) { fuzzy++; return; }
      if (!known.has(e.id)) { skipped++; return; }
      I.set(project, e.id, code, e.str); imported++;
    });
    return { imported, skipped, fuzzy };
  };
})(RVN);
