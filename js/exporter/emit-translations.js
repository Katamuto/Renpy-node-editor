/* Translations -> Ren'Py:
   - game/tl/<code>/rvn_strings.rpy   standard "translate <code> strings:" blocks (old / new)
   - game/rvn_translations.rpy        config.say_menu_text_filter = _  so dialogue and menu texts go through the same string tables
   - language picker                  inserted into the Preferences screen of screens.rpy (radio buttons using Language(...)) */
(function (R) {
  const U = R.util, I = R.i18n;

  R.emitTranslations = function (project) {
    const T = project.translations, langs = T.languages.filter(l => U.ident(l.code, ''));
    if (!langs.length) return null;
    const entries = I.collect(project), files = [];
    langs.forEach(l => {
      const code = U.ident(l.code, ''), font = R.languageFont(project, l), lines = ['# ' + (l.name || code) + ' translations (generated by Ren\'Py Node Editor)', '', 'translate ' + code + ' strings:', ''];
      let n = 0;
      entries.forEach(e => {
        const t = I.get(project, e.text, l.code); if (!t.trim()) return;
        lines.push('    old "' + U.q(I.key(e.text)) + '"', '    new "' + U.q((font && !e.plain ? font.open : '') + I.key(t) + (font && !e.plain ? font.close : '')) + '"', ''); n++;
      });
      if (n) files.push({ path: 'game/tl/' + code + '/rvn_strings.rpy', text: lines.join('\n') });
    });
    files.push({ path: 'game/rvn_translations.rpy', text:
      '# Makes dialogue and menu texts use the string translations (tl/<language>/rvn_strings.rpy).\ninit python:\n    def rvn_text_filter(s):\n        return _(s)\n    config.say_menu_text_filter = rvn_text_filter\n' });
    return { files, langs };
  };

  // Adds the language buttons to the template's Preferences screen. Returns {text, ok}.
  R.patchPreferences = function (screensText, project) {
    const langs = project.translations.languages.filter(l => U.ident(l.code, ''));
    const anchor = /^([ \t]*)## Additional vboxes of type "radio_pref" or "check_pref" can be\r?\n/m, m = screensText.match(anchor);
    if (!langs.length || !m) return { text: screensText, ok: !langs.length };
    const nl = screensText.includes('\r\n') ? '\r\n' : '\n', p = m[1];
    const block = [p + 'vbox:', p + '    style_prefix "radio"', p + '    label _("Language")',
      p + '    textbutton "' + U.q(project.translations.base || 'English') + '" action Language(None)']
      .concat(langs.map(l => { const f = R.languageFont(project, l); return p + '    textbutton "' + U.q(l.name || l.code) + '" action Language("' + U.ident(l.code, '') + '")' + (f ? ' text_font "' + U.q(f.path) + '"' : ''); })).join(nl) + nl + nl;
    return { text: screensText.replace(anchor, block + m[0]), ok: true };
  };
})(RVN);
