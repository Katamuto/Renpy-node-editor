/* Turns the graph into script.rpy text.
   emitChain() walks a straight path of nodes. At a head node (label) it writes "jump label" and stops.
   Branch nodes (menu, condition) write their header and then recurse into each exit:
     - exit target is a head (merge / loop / label)  -> "jump label"
     - exit target is a normal node                  -> its chain is written inline, indented
   An arm with header:null continues at the same indent (a branch node with a single exit).
   Every chain ends in jump / return, so Ren'Py never falls through into the next label by accident. */
(function (R) {
  const U = R.util, pad = (n) => '    '.repeat(n);

  R.emitScript = function (project) {
    const A = R.analyzeGraph(project), warnings = A.warnings.slice(), lines = [], done = new Set(), lineMap = {};

    const charIds = new Set();
    lines.push('# Generated by Ren\'Py Node Editor. Edit the story in the editor and export again.', '');
    project.characters.forEach(c => {
      const id = U.ident(c.id, '');
      if (!id || charIds.has(id)) { warnings.push({ msg: 'Character "' + c.id + '" has an empty or duplicate id, skipped' }); return; }
      charIds.add(id);
      const args = [c.name ? '_("' + U.qt(c.name) + '")' : 'None'];
      if (c.color) args.push('color="' + U.q(c.color) + '"');
      lines.push('define ' + id + ' = Character(' + args.join(', ') + ')');
    });
    if (project.characters.length) lines.push('');
    const vars = new Set();
    project.variables.forEach(v => {
      const name = U.ident(v.name, '');
      if (!name || vars.has(name)) { if (v.name) warnings.push({ msg: 'Variable "' + v.name + '" is invalid or duplicated, skipped' }); return; }
      vars.add(name); lines.push('default ' + name + ' = ' + (String(v.value).trim() || 'None'));
    });
    if (vars.size) lines.push('');

    const ctx = {
      project,
      warn: (node, msg) => warnings.push({ nodeId: node && node.id, msg }),
      charId: (raw) => { const id = U.ident(raw, ''); return charIds.has(id) ? id : null; },
      labelName: (nodeId) => A.heads.get(nodeId) || null
    };
    const push = (indent, text) => lines.push(pad(indent) + text);

    function armBody(node, port, indent) {
      const target = A.out.get(node.id + '|' + port);
      if (!target) { ctx.warn(node, 'An exit is not connected, the game ends there'); push(indent, 'return'); return; }
      emitChain(target, indent, false);
    }

    function emitChain(startId, indent, first) {
      let cur = startId;
      while (true) {
        const node = A.nodes.get(cur), def = R.registry.get(node.type);
        if (!first && A.heads.has(cur)) { push(indent, 'jump ' + A.heads.get(cur)); return; }
        first = false;
        if (done.has(cur)) { ctx.warn(node, 'Internal: node reached twice, ending game here'); push(indent, 'return'); return; }
        done.add(cur); lineMap[cur] = lines.length + 1;   // source map: first script line of this node (used by "play from here")
        const items = def.branch ? def.branch(node, ctx) : null;
        if (items && items.some(it => typeof it !== 'string')) {     // real branching node: every exit gets its own body
          items.forEach(it => {
            if (typeof it === 'string') push(indent, it);
            else { if (it.header !== null) push(indent + it.headerIndent, it.header); armBody(node, it.port, indent + it.bodyIndent); }
          });
          return;
        }
        (items || (def.emit ? def.emit(node, ctx) : [])).forEach(l => push(indent, l));
        if (def.terminal) return;
        const next = A.out.get(node.id + '|next');
        if (!next) { ctx.warn(node, 'Nothing is connected after this node, the game ends here'); push(indent, 'return'); return; }
        cur = next;
      }
    }

    // --- top level ---
    const t = A.startTarget;
    if (!t) { lines.push('label start:', pad(1) + 'return', ''); }
    else if (A.heads.get(t) === 'start') { lines.push('label start:'); emitChain(t, 1, true); lines.push(''); }
    else if (A.heads.has(t)) { lines.push('label start:', pad(1) + 'jump ' + A.heads.get(t), ''); }
    else { lines.push('label start:'); emitChain(t, 1, false); lines.push(''); }

    A.heads.forEach((name, id) => {
      if (name === 'start') return;
      lines.push('label ' + name + ':'); emitChain(id, 1, true); lines.push('');
    });
    return { text: lines.join('\n').replace(/\n+$/, '\n'), warnings, lineMap };
  };
})(RVN);
