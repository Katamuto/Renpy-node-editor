#!/usr/bin/env python3
"""Regenerate js/io/template-data.js from a Ren'Py empty-project zip.
Usage: python3 tools/build-template.py tools/template.zip
Keeps game/gui, screens.rpy, gui.rpy, options.rpy. Drops generated/runtime stuff (cache, saves, log, tl, script.rpy)."""
import sys, zipfile, base64, json, os
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), 'template.zip')
skip_prefix = ('game/cache/', 'game/saves/', 'game/tl/')
skip_exact = ('log.txt', 'game/script.rpy')
files = {}
with zipfile.ZipFile(src) as z:
    for info in z.infolist():
        if info.is_dir():
            continue
        name = info.filename.split('/', 1)[1]          # strip the top-level "template/" folder
        if name in skip_exact or name.startswith(skip_prefix) or not name.startswith('game/'):
            continue
        files[name] = base64.b64encode(z.read(info)).decode('ascii')
out = os.path.join(os.path.dirname(__file__), '..', 'js', 'io', 'template-data.js')
with open(out, 'w') as f:
    f.write('/* AUTO-GENERATED by tools/build-template.py. Large base64 data: do not open or edit by hand. */\n')
    f.write('(function (R) {\nR.templateFiles = {\n')
    f.write(',\n'.join('%s:"%s"' % (json.dumps(k), v) for k, v in sorted(files.items())))
    f.write('\n};\n})(RVN);\n')
print('wrote', os.path.normpath(out), len(files), 'files,', os.path.getsize(out) // 1024, 'KB')
